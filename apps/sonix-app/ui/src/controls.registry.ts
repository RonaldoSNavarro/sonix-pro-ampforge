import {
  ALL_AMP_MODELS as GENERATED_AMP_MODELS,
  PARAMS_SCHEMA,
  type AmpModelId,
  type BackendParamKey,
  type ParamSchemaEntry,
} from './params.generated.ts';

export type { AmpModelId };

export type ControlKind =
  | 'knob'
  | 'slider'
  | 'toggle'
  | 'switch_3pos'
  | 'select'
  | 'button'
  | 'jack'
  | 'footswitch'
  | 'pad'
  | 'expression'
  | 'action';

export const ALL_AMP_MODELS: AmpModelId[] = [...GENERATED_AMP_MODELS];

function paramMeta(
  key: BackendParamKey,
  uiModelsOverride?: readonly AmpModelId[],
): Pick<ControlDescriptor, 'backendKey' | 'type' | 'range' | 'step' | 'options' | 'defaultValue' | 'models'> {
  const schema = PARAMS_SCHEMA[key] as ParamSchemaEntry;
  const resolvedModels = uiModelsOverride ?? schema.models;
  if (schema.type === 'number') {
    return {
      backendKey: key,
      type: 'number',
      range: [schema.range[0], schema.range[1]],
      step: schema.step,
      defaultValue: schema.defaultValue,
      ...(resolvedModels ? { models: [...resolvedModels] } : {}),
    };
  }
  if (schema.type === 'enum') {
    return {
      backendKey: key,
      type: 'enum',
      options: [...schema.options],
      defaultValue: schema.defaultValue,
      ...(resolvedModels ? { models: [...resolvedModels] } : {}),
    };
  }
  return {
    backendKey: key,
    type: 'boolean',
    defaultValue: schema.defaultValue,
    ...(resolvedModels ? { models: [...resolvedModels] } : {}),
  };
}

export type ScreenId =
  | 'topbar'
  | 'main'
  | 'chassi'
  | 'gabinete'
  | 'audio'
  | 'palco'
  | 'biblioteca';

